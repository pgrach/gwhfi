-- Phase 1: durable telemetry collection lineage.
--
-- This migration is deliberately additive. Existing energy readings retain their
-- legacy columns and values; lineage fields remain NULL for rows written before
-- the collector starts sending the versioned payload.

begin;

-- Keep a fresh local Supabase project usable while leaving an existing production
-- table (including its current primary key) unchanged.
create table if not exists public.energy_readings (
    id bigint generated by default as identity primary key,
    device_id text not null,
    channel integer not null,
    power_w double precision,
    voltage double precision,
    energy_total_wh double precision,
    created_at timestamptz not null default now()
);

create table if not exists public.telemetry_polls (
    poll_id uuid primary key,
    site_id text not null,
    device_id text not null,
    collector_id text not null,
    source text not null default 'shelly_cloud',
    sampling_policy_version integer not null default 1,
    scheduled_at timestamptz,
    request_started_at timestamptz not null,
    received_at timestamptz,
    completed_at timestamptz not null,
    outcome text not null,
    error_code text,
    error_message text,
    latency_ms integer,
    http_status integer,
    poll_sequence bigint,
    payload_hash text,
    raw_payload jsonb,
    created_at timestamptz not null default now(),
    constraint telemetry_polls_source_nonempty_check
        check (btrim(source) <> ''),
    constraint telemetry_polls_site_nonempty_check
        check (btrim(site_id) <> ''),
    constraint telemetry_polls_collector_nonempty_check
        check (btrim(collector_id) <> ''),
    constraint telemetry_polls_sampling_policy_version_check
        check (sampling_policy_version >= 1),
    constraint telemetry_polls_outcome_check
        check (outcome in ('success', 'source_error', 'persistence_error', 'unexpected_error')),
    constraint telemetry_polls_latency_check
        check (latency_ms is null or latency_ms >= 0),
    constraint telemetry_polls_http_status_check
        check (http_status is null or http_status between 100 and 599),
    constraint telemetry_polls_sequence_check
        check (poll_sequence is null or poll_sequence >= 0),
    constraint telemetry_polls_received_order_check
        check (received_at is null or received_at >= request_started_at),
    constraint telemetry_polls_completed_order_check
        check (completed_at >= request_started_at)
);

alter table public.energy_readings
    add column if not exists poll_id uuid,
    add column if not exists site_id text,
    add column if not exists observed_at timestamptz,
    add column if not exists received_at timestamptz,
    add column if not exists collector_id text,
    add column if not exists sample_reason text,
    add column if not exists quality_flags text[],
    add column if not exists schema_version integer;

-- Invalid or absent source measurements are represented as NULL plus an
-- explanatory quality flag. Older deployments declared these columns NOT NULL,
-- so relax them without rewriting any existing values.
alter table public.energy_readings
    alter column power_w drop not null,
    alter column voltage drop not null,
    alter column energy_total_wh drop not null;

comment on table public.telemetry_polls is
    'One immutable collection attempt. Raw readings reference it through energy_readings.poll_id.';
comment on column public.energy_readings.observed_at is
    'Timestamp reported by the source when available; NULL for legacy rows.';
comment on column public.energy_readings.received_at is
    'Timestamp at which the collector received the source response; NULL for legacy rows.';
comment on column public.energy_readings.created_at is
    'Legacy persistence timestamp retained for dashboard and API compatibility.';
comment on column public.energy_readings.sample_reason is
    'Why this sparse sample was retained (for example active, turned_off, or heartbeat).';
comment on column public.energy_readings.quality_flags is
    'Collector-assigned data-quality flags. NULL means unknown legacy quality, not an empty flag set.';
comment on column public.energy_readings.schema_version is
    'Collector payload contract version. NULL identifies legacy rows.';
comment on column public.energy_readings.site_id is
    'Stable installation/site scope. NULL is retained only for legacy rows.';

do $migration$
begin
    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_poll_id_fkey'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_poll_id_fkey
            foreign key (poll_id)
            references public.telemetry_polls (poll_id)
            on delete set null
            not valid;
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_site_nonempty_check'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_site_nonempty_check
            check (site_id is null or btrim(site_id) <> '')
            not valid;
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_v1_site_required_check'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_v1_site_required_check
            check (schema_version is null or site_id is not null)
            not valid;
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_schema_version_check'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_schema_version_check
            check (schema_version is null or schema_version >= 1)
            not valid;
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_sample_reason_check'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_sample_reason_check
            check (
                sample_reason is null
                or sample_reason in (
                    'first',
                    'active',
                    'turned_off',
                    'heartbeat',
                    'periodic',
                    'manual',
                    'recovered'
                )
            )
            not valid;
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_collector_nonempty_check'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_collector_nonempty_check
            check (collector_id is null or btrim(collector_id) <> '')
            not valid;
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.energy_readings'::regclass
          and conname = 'energy_readings_quality_flags_check'
    ) then
        alter table public.energy_readings
            add constraint energy_readings_quality_flags_check
            check (
                quality_flags is null
                or (
                    array_position(quality_flags, null) is null
                    and array_position(quality_flags, '') is null
                )
            )
            not valid;
    end if;
end
$migration$;

