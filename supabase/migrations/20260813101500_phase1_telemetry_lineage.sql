-- Compact cumulative-counter series for energy calculations. Unlike the power
-- RPC, this returns the latest real counter observation in each bucket rather
-- than averaging counters or manufacturing interpolated samples.
drop function if exists public.get_energy_counter_series_for_device(
    timestamptz,
    timestamptz,
    integer,
    text,
    text
);
create function public.get_energy_counter_series_for_device(
    start_time timestamptz,
    end_time timestamptz,
    bucket_seconds integer,
    target_site_id text,
    target_device_id text
)
returns table (
    bucket_time timestamptz,
    device_id text,
    channel integer,
    energy_total_wh double precision,
    created_at timestamptz
)
language plpgsql
stable
security invoker
set search_path = ''
as $function$
begin
    if start_time is null or end_time is null or start_time >= end_time then
        raise exception 'start_time must be earlier than end_time'
            using errcode = '22023';
    end if;
    if bucket_seconds is null or bucket_seconds < 1 or bucket_seconds > 86400 then
        raise exception 'bucket_seconds must be between 1 and 86400'
            using errcode = '22023';
    end if;
    if target_site_id is null or pg_catalog.btrim(target_site_id) = '' then
        raise exception 'target_site_id must not be empty'
            using errcode = '22023';
    end if;
    if target_device_id is null or pg_catalog.btrim(target_device_id) = '' then
        raise exception 'target_device_id must not be empty'
            using errcode = '22023';
    end if;

    return query
    with bucketed as (
        select
            pg_catalog.to_timestamp(
                pg_catalog.floor(
                    extract(epoch from reading.created_at)
                    / bucket_seconds::double precision
                ) * bucket_seconds::double precision
            ) as sample_bucket,
            reading.device_id as sample_device_id,
            reading.channel::integer as sample_channel,
            reading.energy_total_wh::double precision as sample_energy_total_wh,
            reading.created_at as sample_created_at,
            reading.observed_at as sample_observed_at,
            reading.poll_id as sample_poll_id
        from public.energy_readings as reading
        where reading.device_id = target_device_id
          and (reading.site_id = target_site_id or reading.site_id is null)
          and reading.energy_total_wh is not null
          and reading.created_at >= start_time
          and reading.created_at < end_time
    )
    select distinct on (sample.sample_bucket, sample.sample_channel)
        sample.sample_bucket as bucket_time,
        sample.sample_device_id as device_id,
        sample.sample_channel as channel,
        sample.sample_energy_total_wh as energy_total_wh,
        sample.sample_created_at as created_at
    from bucketed as sample
    order by
        sample.sample_bucket,
        sample.sample_channel,
        sample.sample_created_at desc,
        sample.sample_observed_at desc nulls last,
        sample.sample_poll_id desc nulls last;
end
$function$;

