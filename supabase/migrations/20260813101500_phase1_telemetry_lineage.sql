-- A real UNIQUE constraint (rather than a partial index) is required for
-- PostgREST's on_conflict=poll_id,device_id,channel retry contract. PostgreSQL's
-- default NULL-distinct semantics allow duplicate legacy rows whose poll_id is
-- NULL while making every versioned poll/channel insert idempotent.
drop index if exists public.energy_readings_poll_device_channel_uidx;
