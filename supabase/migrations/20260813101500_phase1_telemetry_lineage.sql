-- Canonical legacy RPC used by existing dashboard deployments. It intentionally
-- retains created_at as the bucket clock until every collector writes observed_at.
drop function if exists public.get_downsampled_readings(timestamptz, timestamptz, integer);
create function public.get_downsampled_readings(
    start_time timestamptz,
    end_time timestamptz,
    bucket_seconds integer
)
returns table (
    bucket_time timestamptz,
    channel integer,
    avg_power double precision
)
language plpgsql
stable
security invoker
set search_path = ''
as $function$
begin
    if start_time is null or end_time is null or start_time >= end_time then
        raise exception 'start_time must be earlier than end_time'
            using errcode = '22023';
    end if;
    if bucket_seconds is null or bucket_seconds < 1 or bucket_seconds > 86400 then
        raise exception 'bucket_seconds must be between 1 and 86400'
            using errcode = '22023';
    end if;

    return query
    select
        pg_catalog.to_timestamp(
            pg_catalog.floor(extract(epoch from er.created_at) / bucket_seconds::double precision)
            * bucket_seconds::double precision
        ) as bucket_time,
        er.channel::integer as channel,
        pg_catalog.avg(er.power_w)::double precision as avg_power
    from public.energy_readings as er
    where er.created_at >= start_time
      and er.created_at < end_time
    group by 1, er.channel
    order by 1, er.channel;
end
$function$;

